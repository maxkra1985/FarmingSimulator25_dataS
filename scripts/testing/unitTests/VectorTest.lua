VectorTest = {}
function VectorTest.test_eulerToDirection()
	local v1_, v2_, v3_ = MathUtil.eulerToDirection(0, 1.5707963267948966)
	Assert.areRoughlyEqual(v1_, 0)
	Assert.areRoughlyEqual(v2_, -1)
	Assert.areRoughlyEqual(v3_, 0)
	local v4_, v5_, v6_ = MathUtil.eulerToDirection(0, -1.5707963267948966)
	Assert.areRoughlyEqual(v4_, 0)
	Assert.areRoughlyEqual(v5_, 1)
	Assert.areRoughlyEqual(v6_, 0)
	local v7_, v8_, v9_ = MathUtil.eulerToDirection(1.5707963267948966, 0)
	Assert.areRoughlyEqual(v7_, 1)
	Assert.areRoughlyEqual(v8_, 0)
	Assert.areRoughlyEqual(v9_, 0)
	local v10_, v11_, v12_ = MathUtil.eulerToDirection(-1.5707963267948966, 0)
	Assert.areRoughlyEqual(v10_, -1)
	Assert.areRoughlyEqual(v11_, 0)
	Assert.areRoughlyEqual(v12_, 0)
	local v13_, v14_, v15_ = MathUtil.eulerToDirection(0, 0)
	Assert.areRoughlyEqual(v13_, 0)
	Assert.areRoughlyEqual(v14_, 0)
	Assert.areRoughlyEqual(v15_, 1)
	local v16_, v17_, v18_ = MathUtil.eulerToDirection(3.141592653589793, 0)
	Assert.areRoughlyEqual(v16_, 0)
	Assert.areRoughlyEqual(v17_, 0)
	Assert.areRoughlyEqual(v18_, -1)
	local v19_ = createTransformGroup("test")
	for v20_ = -3.141592653589793, 3.141592653589793, 0.2617993877991494 do
		for v21_ = -3.141592653589793, 3.141592653589793, 0.2617993877991494 do
			setWorldRotation(v19_, v20_, v21_, 0)
			local v22_, v23_, v24_ = MathUtil.eulerToDirection(v21_, v20_)
			local v25_, v26_, v27_ = localDirectionToWorld(v19_, 0, 0, 1)
			Assert.areRoughlyEqual(v22_, v25_)
			Assert.areRoughlyEqual(v23_, v26_)
			Assert.areRoughlyEqual(v24_, v27_)
		end
	end
	delete(v19_)
end
