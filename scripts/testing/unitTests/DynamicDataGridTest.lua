function DynamicDataGridTest.test_size()
	for v56_ = 0, 32 do
		local v57_ = DynamicDataGrid.new(200 + v56_, 16)
		DynamicDataGridTest.testEntireGrid(v57_)
	end
end

-- Local values: localRowIndex, localColumnIndex, rowIndex, columnIndex, rawCell, localCell, worldX, worldZ, localIndexX, localIndexZ, worldCell
function DynamicDataGridTest.testEntireGrid(dataGrid)
	local v59_ = dataGrid.localStartIndex
	local v60_ = dataGrid.localStartIndex
	for v61_ = 1, dataGrid.rowColumnCount do
		for v62_ = 1, dataGrid.rowColumnCount do
			local v63_ = dataGrid.grid[v62_][v61_]
			Assert.isNotNil(v63_, string.format("Indexed cell at %d, %d was nil.", v62_, v61_))
			local v64_ = dataGrid:getCellFromLocalIndices(v60_, v59_)
			Assert.areEqual(v63_, v64_, "Raw indexed cell did not match locally indexed cell at %d, %d", v60_, v59_)
			local v65_, v66_ = dataGrid:getWorldPositionByLocalIndices(v60_, v59_)
			local v67_, v68_ = dataGrid:getLocalIndicesByWorldPosition(v65_, v66_)
			Assert.areEqual(v67_, v60_)
			Assert.areEqual(v68_, v59_)
			local v69_ = dataGrid:getCellFromWorldPosition(v65_, v66_)
			Assert.areEqual(v64_, v69_)
			Assert.areEqual(dataGrid:getCellFromWorldPosition(v65_ + (dataGrid.tileSize / 2 - 1), v66_ + (dataGrid.tileSize / 2 - 1)), v69_)
			Assert.areEqual(dataGrid:getCellFromWorldPosition(v65_ - dataGrid.tileSize / 2, v66_ - dataGrid.tileSize / 2), v69_)
			v60_ = v60_ + 1
		end
		v60_ = dataGrid.localStartIndex
		v59_ = v59_ + 1
	end
end
